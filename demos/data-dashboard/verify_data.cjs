/* Independent comparison with the source-derived reference responses. */
const fs = require("node:fs");
const vm = require("node:vm");
const path = require("node:path");
const assert = require("node:assert/strict");
const source = JSON.parse(fs.readFileSync(path.join(__dirname, "data.json"), "utf8"));
const scope = {window: {ACHATS_DATA: source}, Intl};
vm.runInNewContext(fs.readFileSync(path.join(__dirname, "app.js"), "utf8"), scope);
const api = scope.window.ACHATS_APP;
const result = api.calculate(api.filterCells());
const plain = (value) => JSON.parse(JSON.stringify(value));
assert.deepEqual(plain({total_achats: result.total/100, nb_commandes: result.validatedRows, nb_fournisseurs: result.supplierCount, taux_validation: result.rate}), source.baseline.kpis);
assert.deepEqual(plain(result.monthly.map((r)=>({mois:r.label,total:r.cents/100}))), source.baseline.par_mois);
assert.deepEqual(plain(result.category.map((r)=>({categorie:r.label,total:r.cents/100}))), source.baseline.par_categorie);
assert.deepEqual(plain(result.suppliers.map((r)=>({fournisseur:r.label,total:r.cents/100}))), source.baseline.par_fournisseur);
assert.deepEqual(plain(result.cascade.map((r)=>({label:r.label,value:r.cents/100,type:r.type}))), source.baseline.cascade_budget);
const a = api.calculate(api.filterCells({year:"2023"}));
const b = api.calculate(api.filterCells({year:"2024"}));
assert.equal(a.total+b.total,result.total);
assert.equal(a.totalRows+b.totalRows,200);
assert.equal(a.validatedRows+b.validatedRows,result.validatedRows);
const onlyA = api.calculate(api.filterCells({supplier:"fournisseur a"}));
assert.equal(onlyA.supplierCount,1);
assert.equal(onlyA.suppliers[0].label,"Fournisseur A");
const none = api.calculate(api.filterCells({supplier:"inexistant"}));
assert.equal(none.totalRows,0);
assert.equal(none.total,0);
assert.equal(none.rate,0);
assert.equal(none.cascade.at(-1).cents,50000000);
const services = api.calculate(api.filterCells({category:"Services"}));
assert.equal(services.category.length,1);
assert.equal(services.total,result.category.find((r)=>r.label==="Services").cents);
